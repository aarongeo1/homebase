#!/usr/bin/env node
// Generates docs/CODEMAP.md: every API operation, frontend export, public .NET type and
// database table in one cheap-to-read file. Agents read this INSTEAD of searching the repo,
// and "not in the codemap" means "does not exist". `--check` fails when it is stale (CI).
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { parse } from 'yaml';

const ROOT = path.resolve(import.meta.dirname, '..');
const OUT = path.join(ROOT, 'docs', 'CODEMAP.md');
const SKIP_DIRS = new Set(['node_modules', 'bin', 'obj', 'dist', 'generated', 'coverage', '.vs']);

const rel = (p) => path.relative(ROOT, p).split(path.sep).join('/');
const lineCount = (text) => text.split('\n').length;

function walk(dir, accept) {
  const out = [];
  for (const name of readdirSync(dir).sort()) {
    const full = path.join(dir, name);
    if (statSync(full).isDirectory()) {
      if (!SKIP_DIRS.has(name)) out.push(...walk(full, accept));
    } else if (accept(full)) out.push(full);
  }
  return out;
}

function tsExports(text) {
  const names = new Set();
  const add = (n) => n && names.add(n.trim());
  for (const m of text.matchAll(/^export\s+(?:default\s+)?(?:async\s+)?function\s*\*?\s*([A-Za-z_$][\w$]*)/gm)) add(m[1]);
  for (const m of text.matchAll(/^export\s+(?:const|let|class|enum)\s+([A-Za-z_$][\w$]*)/gm)) add(m[1]);
  for (const m of text.matchAll(/^export\s+(?:interface|type)\s+([A-Za-z_$][\w$]*)/gm)) add(`type ${m[1]}`);
  for (const m of text.matchAll(/^export\s+(type\s+)?\{([^}]*)\}/gm)) {
    for (const part of m[2].split(',')) {
      const name = part.trim().split(/\s+as\s+/).pop();
      if (name) add(m[1] || part.trim().startsWith('type ') ? `type ${name.replace(/^type\s+/, '')}` : name);
    }
  }
  for (const m of text.matchAll(/^export\s+(?:type\s+)?\*\s+from\s+['"]([^'"]+)['"]/gm)) add(`* from ${m[1]}`);
  return [...names];
}

function csPublicTypes(text) {
  return [...text.matchAll(/^\s*public\s+(?:static\s+|sealed\s+|abstract\s+|partial\s+)*(class|interface|enum|struct)\s+(\w+)/gm)].map((m) =>
    m[1] === 'class' ? m[2] : `${m[1]} ${m[2]}`,
  );
}

function section(title, files, describe) {
  const lines = [`## ${title}`, ''];
  for (const file of files) {
    const text = readFileSync(file, 'utf8');
    const items = describe(text);
    lines.push(`- \`${rel(file)}\` (${lineCount(text)} lines)${items.length ? ` — ${items.join(', ')}` : ''}`);
  }
  return [...lines, ''];
}

function apiSection() {
  const spec = parse(readFileSync(path.join(ROOT, 'contracts/openapi.yaml'), 'utf8'));
  const lines = ['## API operations (contracts/openapi.yaml)', ''];
  for (const [p, ops] of Object.entries(spec.paths)) {
    for (const [method, op] of Object.entries(ops)) {
      lines.push(`- \`${method.toUpperCase()} ${p}\` — ${op.operationId}${op.summary ? `: ${op.summary}` : ''}`);
    }
  }
  return [...lines, ''];
}

function databaseSection() {
  const dir = path.join(ROOT, 'database/migrations');
  const files = walk(dir, (f) => f.endsWith('.sql'));
  return section('Database migrations (database/migrations)', files, (text) =>
    [...text.matchAll(/CREATE\s+TABLE\s+(?:\[?dbo\]?\.)?\[?(\w+)\]?/gi)].map((m) => `table ${m[1]}`),
  );
}

function generate() {
  const front = path.join(ROOT, 'frontend/src');
  const isSource = (f) => /\.(ts|tsx)$/.test(f) && !/\.test\.tsx?$/.test(f) && !f.includes(`${path.sep}test${path.sep}`);
  const frontFiles = walk(front, isSource);
  const group = (prefix) => frontFiles.filter((f) => rel(f).startsWith(prefix));
  const domains = readdirSync(path.join(front, 'domains')).sort();

  const backFiles = walk(path.join(ROOT, 'backend'), (f) => f.endsWith('.cs') && !/[\\/]tests[\\/]/.test(f));
  const projects = [...new Set(backFiles.map((f) => rel(f).split('/').slice(0, 3).join('/')))].sort();

  return [
    '<!-- GENERATED by scripts/codemap.mjs — do not edit. Run `npm run codemap`. CI fails if this is stale. -->',
    '# Code map',
    '',
    'Read this before searching. If a file, export, type, endpoint or table is not listed here, it does not exist —',
    'say so instead of guessing. Line counts tell you what a file costs to read. Tests are omitted.',
    '',
    ...apiSection(),
    '# Frontend (frontend/src)',
    '',
    ...section('App shell', group('frontend/src/app'), tsExports),
    ...section('Shared: API client (only way to call the backend)', group('frontend/src/shared/api'), tsExports),
    ...section('Shared: lib', group('frontend/src/shared/lib'), tsExports),
    ...section('Shared: UI kit', group('frontend/src/shared/ui'), tsExports),
    ...domains.flatMap((d) => section(`Domain: ${d}`, group(`frontend/src/domains/${d}/`), tsExports)),
    '# Backend (backend/src)',
    '',
    ...projects.flatMap((p) => section(p.split('/').pop(), backFiles.filter((f) => rel(f).startsWith(`${p}/`)), csPublicTypes)),
    ...databaseSection(),
  ].join('\n');
}

const content = generate();
if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(OUT, 'utf8');
  } catch {
    // Missing file is reported as stale below.
  }
  if (current !== content) {
    console.error('docs/CODEMAP.md is stale. Run: npm run codemap');
    process.exit(1);
  }
  console.log('codemap up to date');
} else {
  writeFileSync(OUT, content);
  console.log(`wrote ${rel(OUT)} (${lineCount(content)} lines)`);
}
